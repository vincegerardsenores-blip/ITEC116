CREATE DATABASE IF NOT EXISTS `10_pmims_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `10_pmims_db`;

CREATE TABLE IF NOT EXISTS `users` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  Email VARCHAR(160) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  Role VARCHAR(30) NOT NULL DEFAULT 'user',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `materials` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `MaterialName` VARCHAR(255) NOT NULL,
  `Unit` VARCHAR(255) NOT NULL,
  `StockQty` DECIMAL(12,2) NOT NULL,
  `ReorderLevel` DECIMAL(12,2) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `work_orders` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `WorkOrderCode` VARCHAR(255) NOT NULL,
  `ProductName` VARCHAR(255) NOT NULL,
  `TargetQuantity` INT NOT NULL,
  `Status` VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `production_logs` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `QuantityProduced` INT NOT NULL,
  `DowntimeMinutes` INT NOT NULL,
  `LoggedAt` DATETIME NULL,
  `WorkOrderID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_production_logs_workorderid` FOREIGN KEY (`WorkOrderID`) REFERENCES `work_orders` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `machine_downtimes` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `MachineName` VARCHAR(255) NOT NULL,
  `Reason` TEXT NOT NULL,
  `StartTime` DATETIME NOT NULL,
  `EndTime` DATETIME NULL,
  `WorkOrderID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_machine_downtimes_workorderid` FOREIGN KEY (`WorkOrderID`) REFERENCES `work_orders` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
